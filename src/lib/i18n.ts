export function resolveLang(setting: "auto" | "zh" | "en"): "zh" | "en" {
  if (setting !== "auto") return setting;
  return (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** The strings of the language a setting stands for, outside a component. */
export function stringsFor(setting: "auto" | "zh" | "en"): Dict {
  return resolveLang(setting) === "zh" ? zh : en;
}

export function useT(): Dict {
  return stringsFor(useStore((s) => s.settings.lang));
}
